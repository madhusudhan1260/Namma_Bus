export type AccessKey = Key;

export function accessT(key: Key, lang: 'EN' | 'KN', vars?: Record<string, string | number>): string {
  let text = (lang === 'KN' ? KN[key] : EN[key]) ?? EN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/** Hook: `const { a, lang } = useAccessT(); a('buyTicket')` */
// The language last rendered by the app, for text produced outside React (e.g. API error messages)
let currentLang: 'EN' | 'KN' = 'EN';
export const accessTCurrent = (key: Key, vars?: Record<string, string | number>) => accessT(key, currentLang, vars);

export function useAccessT() {
  const { preferredLanguage } = useTransit();
  const lang: 'EN' | 'KN' = preferredLanguage === 'KN' ? 'KN' : 'EN';
  currentLang = lang;
  const a = useCallback((key: Key, vars?: Record<string, string | number>) => accessT(key, lang, vars), [lang]);
  return { a, lang };
}
